import {
  getTranslation as getLegacyTranslation,
  localeByLanguage as legacyLocaleByLanguage,
} from "./i18nLegacy";
import type { Language } from "./types";

export type UiLanguage = Language | "pl" | "sk";

type LegacyTranslation = ReturnType<typeof getLegacyTranslation>;
export type Translation = { [Key in keyof LegacyTranslation]: string };

export const uiLanguageChangedEvent = "go-irl-ui-language-changed";
const uiLanguageStorageKey = "go-irl-ui-language";

export const languageOptions: Array<{ id: UiLanguage; shortLabel: string; name: string }> = [
  { id: "ru", shortLabel: "RU", name: "Русский" },
  { id: "uk", shortLabel: "UK", name: "Українська" },
  { id: "cs", shortLabel: "CS", name: "Čeština" },
  { id: "en", shortLabel: "EN", name: "English" },
  { id: "pl", shortLabel: "PL", name: "Polski" },
  { id: "sk", shortLabel: "SK", name: "Slovenčina" },
];

export const localeByLanguage: Record<UiLanguage, string> = {
  ...legacyLocaleByLanguage,
  pl: "pl-PL",
  sk: "sk-SK",
};

const supportedUiLanguages = new Set<UiLanguage>(languageOptions.map((option) => option.id));

export const contentLanguageForUi = (language: UiLanguage): Language => {
  if (language === "pl") return "en";
  if (language === "sk") return "cs";
  return language;
};

export const getStoredUiLanguage = (fallback: Language): UiLanguage => {
  if (typeof window === "undefined") return fallback;
  const stored = window.localStorage.getItem(uiLanguageStorageKey) as UiLanguage | null;
  return stored && supportedUiLanguages.has(stored) ? stored : fallback;
};

export const setUiLanguage = (language: UiLanguage) => {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(uiLanguageStorageKey, language);
  document.documentElement.lang = language;
  window.dispatchEvent(new CustomEvent(uiLanguageChangedEvent, { detail: language }));
};

